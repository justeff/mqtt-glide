#!/usr/bin/env python3
"""Render CONFORMANCE.md: every MQTT 5.0 normative statement, its scope for this client, and
the tests and code that reference it.

Evidence is found by scanning `src/` and `tests/` for `[MQTT-x.y.z-n]` references. A reference in
a test function (its doc comment, attributes or body) counts as a test; anywhere else it counts as
code that implements the statement.

Usage:
    python3 conformance/render.py          # rewrite CONFORMANCE.md
    python3 conformance/render.py --check  # fail if CONFORMANCE.md is stale or a reference is unknown
"""

import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STATEMENTS = ROOT / "conformance" / "statements.tsv"
OUTPUT = ROOT / "CONFORMANCE.md"
SPEC_URL = "https://docs.oasis-open.org/mqtt/mqtt/v5.0/os/mqtt-v5.0-os.html"

REF = re.compile(r"MQTT-(\d+(?:\.\d+)*-\d+)")
FN = re.compile(r"^(\s*)(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+(\w+)")
TEST_ATTR = re.compile(r"^\s*#\[(?:tokio::)?test\b|^\s*#\[rstest\b")


def load_statements():
    rows = []
    for line in STATEMENTS.read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        sid, scope, note, text = line.split("\t")
        rows.append({"id": sid.removeprefix("MQTT-"), "scope": scope, "note": note, "text": text})
    return rows


def is_preamble(line, indent):
    """Doc comments, comments and attributes above a `fn` (including multi-line attribute
    arguments, which rustfmt indents deeper than the `fn`)."""
    stripped = line.strip()
    if not stripped:
        return False
    if stripped.startswith(("//", "#[", ")]", "]")):
        return True
    return len(line) - len(line.lstrip()) > len(indent)


def test_spans(lines):
    """`(start, end, name)` for every test function: from the first line of its doc comment /
    attribute block to its closing brace (rustfmt puts it at the `fn`'s indent)."""
    spans = []
    for i, line in enumerate(lines):
        match = FN.match(line)
        if not match:
            continue
        indent, name = match.group(1), match.group(2)
        start = i
        while start > 0 and is_preamble(lines[start - 1], indent):
            start -= 1
        if not any(TEST_ATTR.match(lines[j]) for j in range(start, i)):
            continue
        end = i
        if not line.rstrip().endswith("}"):
            end = next((j for j in range(i + 1, len(lines)) if lines[j] == f"{indent}}}"), len(lines) - 1)
        spans.append((start, end, name))
    return spans


def scan():
    tests, code = defaultdict(set), defaultdict(set)
    for path in sorted([*ROOT.glob("src/**/*.rs"), *ROOT.glob("tests/**/*.rs")]):
        rel = path.relative_to(ROOT).as_posix()
        lines = path.read_text().splitlines()
        spans = test_spans(lines)
        for i, line in enumerate(lines):
            for sid in REF.findall(line):
                owner = next((name for start, end, name in spans if start <= i <= end), None)
                if owner:
                    tests[sid].add(f"{rel}::{owner}")
                else:
                    code[sid].add(rel)
    return tests, code


def status(row, tests, code):
    if row["scope"] == "server":
        return "server"
    if row["scope"] == "unsupported":
        return "unsupported"
    if tests.get(row["id"]):
        return "tested"
    if code.get(row["id"]):
        return "implemented"
    return "open"


LABEL = {
    "tested": "✅ tested",
    "implemented": "🟡 implemented, no test names it",
    "open": "❌ no reference",
    "server": "— server obligation",
    "unsupported": "— not supported",
}


def evidence(row, tests, code):
    items = sorted(tests.get(row["id"], ()))
    shown = [f"`{t.split('::', 1)[1]}` ({t.split('::', 1)[0]})" for t in items[:3]]
    if len(items) > 3:
        shown.append(f"+{len(items) - 3} more")
    if not items and code.get(row["id"]):
        shown = [f"{c}" for c in sorted(code[row["id"]])[:3]]
    if row["note"]:
        shown.insert(0, row["note"])
    return "<br>".join(shown)


def render(rows, tests, code):
    counts = defaultdict(int)
    for row in rows:
        counts[status(row, tests, code)] += 1
    client_total = counts["tested"] + counts["implemented"] + counts["open"]
    out = [
        "# MQTT 5.0 conformance",
        "",
        "<!-- Generated by `python3 conformance/render.py`; edit `conformance/statements.tsv` or the tests instead. -->",
        "",
        f"Every normative statement of the [MQTT 5.0 OASIS Standard]({SPEC_URL}) (Appendix B, {len(rows)} statements),",
        "with its scope for a client and the tests that check it. Tests and code cite statements as",
        "`[MQTT-x.y.z-n]`; this page is generated from those references, so a statement counts as tested",
        "only when a test names it.",
        "",
        "| | Statements |",
        "|---|---:|",
        f"| Binding a client (or both peers, the sender, the receiver) | {client_total} |",
        f"| … ✅ named by at least one test | {counts['tested']} |",
        f"| … 🟡 implemented, cited only in library code | {counts['implemented']} |",
        f"| … ❌ no reference yet | {counts['open']} |",
        f"| Binding only the Server | {counts['server']} |",
        f"| Part of a feature this client does not implement (QoS 2, enhanced authentication) | {counts['unsupported']} |",
        "",
        "Scope is assigned in `conformance/statements.tsv`. Server obligations are listed for completeness;",
        "where the client relies on one (for example the order of SUBACK reason codes) the client side is",
        "covered by the statement that binds the client.",
        "",
    ]
    by_section = defaultdict(list)
    for row in rows:
        by_section[".".join(row["id"].split("-")[0].split(".")[:2])].append(row)
    for section, section_rows in by_section.items():
        out += [f"## {section}", "", "| Statement | Status | Evidence |", "|---|---|---|"]
        for row in section_rows:
            text = row["text"].replace("|", "\\|")
            out.append(f"| **[MQTT-{row['id']}]** {text} | {LABEL[status(row, tests, code)]} | {evidence(row, tests, code)} |")
        out.append("")
    out += [
        "---",
        "",
        "Statement text quoted from *MQTT Version 5.0*, OASIS Standard, 07 March 2019. Copyright © OASIS",
        "Open 2019. All Rights Reserved. Quoted under the OASIS IPR Policy, which permits derivative works",
        "that assist in the implementation of the specification.",
        "",
    ]
    return "\n".join(out)


def main():
    rows = load_statements()
    tests, code = scan()
    known = {row["id"] for row in rows}
    unknown = sorted((set(tests) | set(code)) - known)
    text = render(rows, tests, code)
    if "--check" in sys.argv:
        problems = []
        if unknown:
            problems.append(f"references to statements that do not exist in MQTT 5.0: {', '.join(unknown)}")
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            problems.append("CONFORMANCE.md is stale; run `python3 conformance/render.py`")
        for problem in problems:
            print(f"conformance: {problem}", file=sys.stderr)
        sys.exit(1 if problems else 0)
    if unknown:
        print(f"warning: unknown statement references: {', '.join(unknown)}", file=sys.stderr)
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
